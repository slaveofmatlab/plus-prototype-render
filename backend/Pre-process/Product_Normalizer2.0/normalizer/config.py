def _load_spec_words_from_excel():
    """
    从 Excel 文件加载规格词库
    
    Excel格式：
    - A列：分类（不能为空）
    - B列：词条（不能为空）
    - C列：备注（可空）
    - 第1行为表头，自动跳过
    
    Returns:
        list: 词条列表，如果加载失败返回None
    """
    if not os.path.exists(_SPEC_WORDS_EXCEL):
        return None
    try:
        import openpyxl
        wb = openpyxl.load_workbook(_SPEC_WORDS_EXCEL, read_only=True)
        ws = wb.active
        words = []
        for row_idx, row in enumerate(ws.iter_rows(min_row=2, values_only=True), 2):
            if row and len(row) >= 2:
                category = row[0]
                word = row[1]
                if category and word:
                    word_str = str(word).strip()
                    if word_str:
                        words.append(word_str)
        wb.close()
        if words:
            print(f"[config] 从Excel加载词库成功: {len(words)}个词条")
            return words
        else:
            print(f"[config] Excel词库为空，回退到内置词库")
            return None
    except ImportError:
        print("[config] 未安装openpyxl，无法加载Excel词库，使用内置词库")
        return None
    except Exception as e:
        print(f"[config] 加载Excel词库失败({e})，回退到内置词库")
        return None


