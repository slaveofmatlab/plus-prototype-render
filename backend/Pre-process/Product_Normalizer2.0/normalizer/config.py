def _load_detail_words_from_excel():
    """
    从 detail_words_dict.xlsx 加载属性词库
    
    Excel格式：
    - A列：分类（加工方式/品质等级等）
    - B列：词条
    - C列：备注
    
    Returns:
        list: 属性词条列表（按长度降序），加载失败返回空列表
    """
    if not os.path.exists(_DETAIL_WORDS_EXCEL):
        return []
    try:
        import openpyxl
        wb = openpyxl.load_workbook(_DETAIL_WORDS_EXCEL, read_only=True)
        ws = wb.active
        words = []
        for row in ws.iter_rows(min_row=2, values_only=True):
            if row and len(row) >= 2:
                category = row[0]
                word = row[1]
                if category and word:
                    word_str = str(word).strip()
                    if word_str:
                        words.append(word_str)
        wb.close()
        if words:
            # 按长度降序，保证最长匹配优先
            words = sorted(set(words), key=len, reverse=True)
            print(f"[config] 从Excel加载属性词库成功: {len(words)}个词条")
            return words
        return []
    except Exception as e:
        print(f"[config] 加载属性词库失败({e})")
        return []


